// Builds the rotating hallway's corridor (src/world/hallway/hallway.glb and manifest.ts) in Blender.
//
//   node scripts/pack-hallway.mjs [--size 1024] [--samples 512] [--blender path] [--python path] [--quality 92] [--reuse]
//
// Blender builds, lights and bakes the corridor from art/hallway/build_hallway.py (nothing is
// downloaded: the model and its light are made from numbers there), and glTF-Transform then
// compresses the geometry (meshopt) and the lightmap (WebP).
//
// Blender: a Blender 5.3 executable (--blender, $BLENDER, or `blender` on the PATH), or a Python
// with the bpy module (--python or $BPY_PYTHON; `pip install bpy==5.3.0` gives one on Python
// 3.13). The bake runs on the CPU: about seven minutes at the default size and samples on four
// cores. --size 512 --samples 32 makes a quick draft in seconds. --reuse skips the bake and
// encodes the last one's light again (art/hallway/out/lightmap.exr), for when only the encoding
// or the export has changed.
//
// glTF-Transform is fetched by npx (@gltf-transform/cli); it is not a dependency of the game.
import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (name, fallback) => (args.includes(`--${name}`) ? args[args.indexOf(`--${name}`) + 1] : fallback);
const size = Number(flag('size', '1024'));
const samples = Number(flag('samples', '512'));
const quality = Number(flag('quality', '92'));
const art = join(root, 'art', 'hallway');
const out = join(art, 'out');
const dest = join(root, 'src', 'world', 'hallway');
const GT = '@gltf-transform/cli@4.5.1';
mkdirSync(out, { recursive: true });
mkdirSync(dest, { recursive: true });

function blender() {
  const exe = flag('blender', process.env.BLENDER);
  const py = flag('python', process.env.BPY_PYTHON);
  const script = join(art, 'build_hallway.py');
  const opts = ['--', '--size', String(size), '--samples', String(samples), '--out', out, ...(args.includes('--reuse') ? ['--reuse'] : [])];
  if (py) return [py, [script, ...opts.slice(1)]];
  if (exe || spawnSync('blender', ['--version']).status === 0) return [exe ?? 'blender', ['-b', '--factory-startup', '-P', script, ...opts]];
  console.error('Needs Blender 5.3: pass --blender path/to/blender, or --python with a Python that has the bpy module.');
  process.exit(1);
}

const [cmd, cmdArgs] = blender();
console.log(`building and baking the corridor (${size} x ${size}, ${samples} samples)...`);
const t0 = Date.now();
const run = spawnSync(cmd, cmdArgs, { stdio: ['ignore', 'pipe', 'inherit'], encoding: 'utf8', maxBuffer: 64 << 20 });
const log = run.stdout ?? '';
for (const line of log.split('\n')) if (/^(built|quarter|baked|lightmap|exported)/.test(line)) console.log(`  ${line}`);
if (run.status !== 0 || !existsSync(join(out, 'hallway-raw.glb'))) {
  console.error(log.slice(-4000));
  console.error('Blender did not finish.');
  process.exit(1);
}
console.log(`  (${((Date.now() - t0) / 1000).toFixed(0)} s)`);

// Compress: meshopt for the geometry (quantised: millimetres over the corridor), WebP for the light.
// No simplifying (the walked-on planes must stay where they are) and no welding across kinds.
const raw = join(out, 'hallway-raw.glb');
const mid = join(out, 'hallway-mid.glb');
const glb = join(dest, 'hallway.glb');
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const gt = (...a) => execFileSync(npx, ['--yes', GT, ...a], { stdio: 'inherit', shell: process.platform === 'win32' });
gt('webp', raw, mid, '--quality', String(quality), '--effort', '90');
gt('optimize', mid, glb, '--compress', 'meshopt', '--texture-compress', 'false', '--simplify', 'false', '--palette', 'false', '--instance', 'false', '--prune-attributes', 'false', '--flatten', 'false');

const info = JSON.parse(readFileSync(join(out, 'hallway.json'), 'utf8'));
const bytes = statSync(glb).size;
copyFileSync(join(out, 'hallway.blend'), join(art, 'hallway.blend'));
writeFileSync(
  join(dest, 'manifest.ts'),
  `// Generated by scripts/pack-hallway.mjs from art/hallway/build_hallway.py. Do not edit by hand.\n` +
    `// lightScale: the light (in Blender's units) that is 1.0 in the lightmap.\n` +
    `export const HALLWAY = ${JSON.stringify({ lightScale: Math.round(info.lightScale * 10000) / 10000, size: info.size, samples: info.samples, triangles: info.triangles * 4, vertices: info.vertices * 4, bytes })} as const;\n`,
);
console.log(`src/world/hallway/hallway.glb  ${(bytes / 1024).toFixed(0)} kB, ${info.triangles * 4} triangles in the whole corridor`);
