// Builds the street life kit (src/city/street/street.glb and manifest.ts) in Blender.
//
//   node scripts/pack-street.mjs [--blender path] [--python path] [--preview]
//
// Blender models every piece from art/street/build_street.py (nothing is downloaded: the models
// are made from numbers there) and exports them as one glTF file, one mesh per piece; glTF-Transform
// then compresses the geometry (meshopt). --preview also renders a line-up of the pieces in Cycles
// (art/street/out/lineup-*.png), for looking at them without the game.
//
// Blender: a Blender 5.3 executable (--blender, $BLENDER, or `blender` on the PATH), or a Python
// with the bpy module (--python or $BPY_PYTHON; `pip install bpy==5.3.0` gives one on Python
// 3.13). It takes a few seconds (a minute or two with --preview).
//
// glTF-Transform is fetched by npx (@gltf-transform/cli); it is not a dependency of the game.
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (name, fallback) => (args.includes(`--${name}`) ? args[args.indexOf(`--${name}`) + 1] : fallback);
const art = join(root, 'art', 'street');
const out = join(art, 'out');
const dest = join(root, 'src', 'city', 'street');
const GT = '@gltf-transform/cli@4.5.1';
mkdirSync(out, { recursive: true });
mkdirSync(dest, { recursive: true });

function blender() {
  const exe = flag('blender', process.env.BLENDER);
  const py = flag('python', process.env.BPY_PYTHON);
  const script = join(art, 'build_street.py');
  const opts = ['--', '--out', out, ...(args.includes('--preview') ? ['--preview'] : [])];
  if (py) return [py, [script, ...opts.slice(1)]];
  if (exe || spawnSync('blender', ['--version']).status === 0) return [exe ?? 'blender', ['-b', '--factory-startup', '-P', script, ...opts]];
  console.error('Needs Blender 5.3: pass --blender path/to/blender, or --python with a Python that has the bpy module.');
  process.exit(1);
}

const [cmd, cmdArgs] = blender();
console.log('modelling the street life kit...');
const t0 = Date.now();
const run = spawnSync(cmd, cmdArgs, { stdio: ['ignore', 'pipe', 'inherit'], encoding: 'utf8', maxBuffer: 64 << 20 });
const log = run.stdout ?? '';
for (const line of log.split('\n')) if (/^(built|rendered|exported)/.test(line)) console.log(`  ${line}`);
if (run.status !== 0 || !existsSync(join(out, 'street-raw.glb'))) {
  console.error(log.slice(-4000));
  console.error('Blender did not finish.');
  process.exit(1);
}
console.log(`  (${((Date.now() - t0) / 1000).toFixed(0)} s)`);

// Compress: meshopt, quantised (millimetres are plenty for street furniture). Every piece stays its own
// mesh (no joining, no instancing, no flattening), and nothing is simplified.
const raw = join(out, 'street-raw.glb');
const glb = join(dest, 'street.glb');
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
execFileSync(
  npx,
  ['--yes', GT, 'optimize', raw, glb, '--compress', 'meshopt', '--texture-compress', 'false', '--simplify', 'false', '--join', 'false', '--palette', 'false', '--instance', 'false', '--prune-attributes', 'false', '--flatten', 'false'],
  { stdio: 'inherit', shell: process.platform === 'win32' },
);

const info = JSON.parse(readFileSync(join(out, 'street.json'), 'utf8'));
const bytes = statSync(glb).size;
const models = Object.fromEntries(Object.entries(info.models).map(([name, m]) => [name, { triangles: m.triangles, min: m.min, max: m.max }]));
writeFileSync(
  join(dest, 'manifest.ts'),
  `// Generated by scripts/pack-street.mjs from art/street/build_street.py. Do not edit by hand.\n` +
    `// Each model's triangles and its bounds (metres, the game's axes: +z is its front).\n` +
    `export const STREET = ${JSON.stringify({ bytes, models }, null, 2)} as const;\n`,
);
const total = Object.values(models).reduce((n, m) => n + m.triangles, 0);
console.log(`src/city/street/street.glb  ${(bytes / 1024).toFixed(0)} kB, ${Object.keys(models).length} models, ${total} triangles in all`);
